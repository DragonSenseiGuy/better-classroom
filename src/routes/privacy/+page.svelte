		<h2>Who uses this app</h2>
		<p>
			The app is intended for individual use. The instance at classroom.mahadk.com is hosted by me
			for myself and people I know. Anyone can also run their own copy from the source code. Each
			person signs in with their own account and only ever sees their own data.
		</p>

		<h2>What data the app accesses</h2>
		<p>
			With your permission, the app reads the following from Google Classroom using read-only
			scopes:
		</p>
		<ul>
			<li>The list of courses you are enrolled in, including course names and teachers.</li>
			<li>Announcements, coursework, materials and topics posted in those courses.</li>
			<li>Your own submission status and grades for coursework.</li>
			<li>Your basic profile: name and email address.</li>
		</ul>
		<p>
			If you choose to connect it, the app can also turn in assignments and post comments on your
			behalf. It never accesses other students' submissions or grades.
		</p>

		<h2>How the data is used</h2>
		<p>
			Data is used solely to show you your own Classroom content inside the app: an inbox of recent
			posts, a to-do list of upcoming work, and course pages. It is not used for advertising,
			analytics, profiling, or training any model, and it is not sold.
		</p>

		<h2>Where the data is stored</h2>
		<p>
			Each account has its own database on the server that runs the app. Credentials you connect,
			such as an Apps Script key or a Classroom session cookie, are stored encrypted. Nothing is
			sent to any third party. The only external services the app communicates with are Google's own
			APIs and your Apps Script deployment, in order to fetch your data.
		</p>

		<h2>Sharing</h2>
		<p>
			Your Google user data is not shared with, transferred to, or disclosed to anyone. It is not
			shared with third parties for any purpose.
		</p>


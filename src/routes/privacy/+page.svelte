		</p>

		<h2>Retention and deletion</h2>
		<p>
			Data stays in your account's database until it is deleted. To remove it, email me at the
			address below and I will delete your account and its database. If you self-host, delete the
			app's data directory (by default <code>data/</code>). To revoke the app's access to your
			Google account, visit
			<a href="https://myaccount.google.com/permissions">myaccount.google.com/permissions</a> and remove
			Better Classroom. Revoking access stops all further data retrieval immediately.
		</p>

		<h2>Security</h2>
